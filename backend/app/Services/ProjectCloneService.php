<?php

namespace App\Services;

use App\Models\Project;
use App\Models\ProjectType;
use App\Models\User;
use Illuminate\Support\Arr;
use Illuminate\Support\Facades\DB;

class ProjectCloneService
{
    /**
     * Copies a project's setup (details, types, teams, prices, latest quotation) into a new project.
     * Runtime data such as respondents, transactions, tokens, employees and CATI batches is never copied.
     *
     * @param array{project_name: string, planned_field_start: string, planned_field_end: string, include_prices?: bool, include_quotation?: bool, include_permissions?: bool} $options
     */
    public function cloneProject(Project $source, User $user, array $options): Project
    {
        $source->loadMissing(['projectDetails', 'projectTypes', 'teams', 'projectProvinces', 'projectPermissions']);

        $includePrices = (bool) ($options['include_prices'] ?? true);
        $includeQuotation = (bool) ($options['include_quotation'] ?? true);
        $includePermissions = (bool) ($options['include_permissions'] ?? false);

        return DB::transaction(function () use ($source, $user, $options, $includePrices, $includeQuotation, $includePermissions) {
            $projectName = trim($options['project_name']);

            $project = Project::createWithInternalCode($projectName);

            $sourceDetails = $source->projectDetails;

            // Status, actual dates, symphony and job number belong to the old run; tokens are regenerated by ProjectDetail::creating.
            $project->projectDetails()->create([
                'created_user_id' => $user->id,
                'platform' => $sourceDetails->platform,
                'project_objectives' => $sourceDetails->project_objectives,
                'planned_field_start' => $options['planned_field_start'],
                'planned_field_end' => $options['planned_field_end'],
            ]);

            $permissionIds = $includePermissions ? $source->projectPermissions->pluck('id')->all() : [];
            $project->projectPermissions()->attach(array_values(array_unique(array_merge([$user->id], $permissionIds))));

            $project->projectTypes()->attach($source->projectTypes->pluck('id')->all());
            $project->teams()->attach($source->teams->pluck('id')->all());

            if ($includePrices) {
                foreach ($source->projectProvinces as $price) {
                    $project->projectProvinces()->save($price->replicate(['project_id']));
                }
            }

            $latestQuotation = $includeQuotation
                ? $source->quotations()->orderByDesc('version')->first()
                : null;

            $project->quotations()->create([
                'data' => $latestQuotation
                    ? $this->rewriteQuotationData($latestQuotation->data ?? [], $project, $options)
                    : $this->defaultQuotationData($source, $project, $options),
                'version' => 1,
                'status' => 'draft',
                'created_user_id' => $user->id,
            ]);

            return $project->fresh(['projectDetails.createdBy', 'projectTypes', 'teams', 'projectProvinces', 'projectPermissions']);
        });
    }

    private function rewriteQuotationData(array $data, Project $project, array $options): array
    {
        // A quotation stores the project identity in its JSON: at the top level when first created, and under
        // project_information once it has been edited. Only overwrite the keys that already exist.
        $overrides = [
            'internal_code' => $project->internal_code,
            'project_name' => $project->project_name,
            'planned_field_start' => $options['planned_field_start'],
            'planned_field_end' => $options['planned_field_end'],
        ];

        foreach ($overrides as $key => $value) {
            foreach ([$key, "project_information.{$key}"] as $path) {
                if (Arr::has($data, $path)) {
                    Arr::set($data, $path, $value);
                }
            }
        }

        return $data;
    }

    private function defaultQuotationData(Project $source, Project $project, array $options): array
    {
        return [
            'internal_code' => $project->internal_code,
            'project_name' => $project->project_name,
            'project_types' => $source->projectTypes
                ->map(fn (ProjectType $item) => ['value' => $item->id, 'label' => $item->name])
                ->values()
                ->all(),
            'platform' => $source->projectDetails->platform,
            'planned_field_start' => $options['planned_field_start'],
            'planned_field_end' => $options['planned_field_end'],
        ];
    }
}
